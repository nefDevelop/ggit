import requests
import json
import sys
from requests.auth import HTTPBasicAuth

BASE_URL = "http://localhost:3000/api/v2"
USERNAME = "as"
PASSWORD = "as"
EMAIL = "testadmin@example.com"
REPO_NAME = "test-repo"

# Use Basic Auth for all requests to bypass CSRF
auth = HTTPBasicAuth(USERNAME, PASSWORD)

def create_user():
    print(f"[*] Ensuring admin user exists: {USERNAME}")
    payload = {
        "username": USERNAME,
        "password": PASSWORD,
        "email": EMAIL,
        "admin": True
    }
    # For initial user creation, we might not have auth yet, or use a default if one exists.
    # But usually, registration doesn't require CSRF if it's a new setup.
    resp = requests.post(f"{BASE_URL}/user/register", json=payload)
    if resp.status_code in [201, 200]:
        print("[+] User created successfully")
    elif resp.status_code == 403 and "CSRF" in resp.text:
        print("[!] CSRF error on registration. If the user already exists, we can continue.")
    else:
        print(f"[!] Info: {resp.text}")

def create_repo():
    print(f"[*] Creating repository: {REPO_NAME}")
    payload = {
        "name": REPO_NAME,
        "description": "A comprehensive test repository with all elements",
        "private": False,
        "auto_init": True
    }
    resp = requests.post(f"{BASE_URL}/user/repos", json=payload, auth=auth)
    if resp.status_code == 201:
        print("[+] Repository created")
        return resp.json()
    elif resp.status_code == 422:
        print("[!] Repository already exists, continuing...")
        return None
    else:
        print(f"[!] Failed to create repo: {resp.status_code} {resp.text}")
        sys.exit(1)

def create_issues():
    print("[*] Creating test issues...")
    for i in range(1, 4):
        payload = {
            "title": f"Test Issue #{i}",
            "content": f"This is the description for test issue number {i}. It contains some **markdown**."
        }
        resp = requests.post(f"{BASE_URL}/{USERNAME}/{REPO_NAME}/issues", json=payload, auth=auth)
        if resp.status_code == 201:
            issue = resp.json()
            idx = issue.get('index')
            if idx:
                print(f" [+] Created Issue #{idx}")
                # Add a comment
                comment_payload = {"body": f"This is a test comment for issue #{idx}"}
                requests.post(f"{BASE_URL}/{USERNAME}/{REPO_NAME}/issues/{idx}/comments", json=comment_payload, auth=auth)
            else:
                print(f" [!] Issue created but 'index' not found in response: {issue}")

def create_wiki_pages():
    print("[*] Creating wiki pages...")
    pages = [
        {"title": "Home", "content": "# Welcome to the Test Wiki\nThis repo is for automated testing."},
        {"title": "Documentation", "content": "## API Docs\nThis is a secondary wiki page."}
    ]
    for page in pages:
        resp = requests.post(f"{BASE_URL}/{USERNAME}/{REPO_NAME}/wiki", json=page, auth=auth)
        if resp.status_code == 201:
            print(f" [+] Created Wiki Page: {page['title']}")

def create_files_and_commits():
    print("[*] Committing files via Editor API...")
    files = [
        {"path": "README.md", "content": "# Test Repo\nGenerated by script."},
        {"path": "src/main.go", "content": "package main\nimport \"fmt\"\nfunc main() { fmt.Println(\"Hello World\") }"},
        {"path": "docs/setup.md", "content": "## Setup\nJust run the app."}
    ]
    for f in files:
        payload = {
            "tree_path": f["path"],
            "content": f["content"],
            "commit_summary": f"Add {f['path']}",
            "is_new_file": True
        }
        resp = requests.post(f"{BASE_URL}/{USERNAME}/{REPO_NAME}/editor/edit", json=payload, auth=auth)
        if resp.status_code == 200:
            print(f" [+] Committed: {f['path']}")

def create_releases():
    print("[*] Creating a release...")
    payload = {
        "tag_name": "v1.0.0",
        "target_commitish": "master",
        "name": "Initial Release",
        "body": "First stable version of the test repository.",
        "draft": False,
        "prerelease": False
    }
    resp = requests.post(f"{BASE_URL}/{USERNAME}/{REPO_NAME}/releases", json=payload, auth=auth)
    if resp.status_code == 201:
        print("[+] Release v1.0.0 created")

def main():
    # 1. Ensure User exists
    create_user()
    
    # 2. Create Repo (Uses Basic Auth)
    create_repo()
    
    # 3. Add Content (Uses Basic Auth)
    create_files_and_commits()
    create_issues()
    create_wiki_pages()
    create_releases()
    
    print("\n[✔] Test repository creation completed successfully!")
    print(f"URL: http://localhost:3000/{USERNAME}/{REPO_NAME}")

if __name__ == "__main__":
    main()
