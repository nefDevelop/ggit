<script lang="ts">
  import { onMount } from 'svelte';
  import { fly } from 'svelte/transition';

  let stats = $state<any>(null);
  let loading = $state(true);
  let runningOp = $state<number | null>(null);
  let feedback = $state<{ msg: string; type: 'success' | 'error' } | null>(null);

  const operations = [
    { id: 1, name: 'Clean Inactive Accounts', icon: 'person_remove', desc: 'Permanently delete accounts that have not been activated.' },
    { id: 2, name: 'Clean Repository Archives', icon: 'archive', desc: 'Remove all repository archives (ZIP, TAR.GZ, etc.) generated by users.' },
    { id: 3, name: 'Clean Missing Repositories', icon: 'folder_off', desc: 'Remove repository records that have lost their physical Git files.' },
    { id: 4, name: 'Git Garbage Collection', icon: 'auto_fix_high', desc: 'Run "git gc" across all repositories to optimize storage.' },
    { id: 5, name: 'Resync SSH Keys', icon: 'vpn_key', desc: 'Rewrite the ".ssh/authorized_keys" file with Ggit keys (warning: removes non-Ggit keys).' },
    { id: 6, name: 'Resync Repository Hooks', icon: 'link', desc: 'Resync all Git hooks across all repositories.' },
    { id: 7, name: 'Reinitialize Missing Repos', icon: 'reorder', desc: 'Reinitialize Git files for identified missing repository records.' },
  ];

  async function fetchStats() {
    try {
      const res = await fetch('/api/v2/admin/stats');
      if (res.ok) {
        stats = await res.json();
      }
    } catch (e) {
      console.error(e);
    } finally {
      loading = false;
    }
  }

  async function runOperation(opId: number) {
    if (runningOp !== null) return;
    runningOp = opId;
    feedback = null;
    
    try {
      const res = await fetch('/api/v2/admin/operations', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ op: opId })
      });
      const data = await res.json();
      if (res.ok) {
        feedback = { msg: 'Operation executed successfully!', type: 'success' };
        await fetchStats(); // Refresh stats if needed
      } else {
        feedback = { msg: data.error || 'Operation failed.', type: 'error' };
      }
    } catch (e) {
      feedback = { msg: 'Network error.', type: 'error' };
    } finally {
      runningOp = null;
    }
  }

  onMount(fetchStats);
</script>

<div class="maintenance-view" in:fly={{ y: 20, duration: 400 }}>
  <header class="section-header">
    <div class="header-content">
      <h2>Server Maintenance</h2>
      <p class="subtitle">Optimize, clean, and monitor the health of your Ggit instance.</p>
    </div>
    {#if stats?.system?.uptime}
      <div class="uptime-badge island">
        <span class="material-icons">timer</span>
        <span>Uptime: {stats.system.uptime}</span>
      </div>
    {/if}
  </header>

  {#if loading}
    <div class="skeleton-maintenance island"></div>
  {:else if stats}
    <div class="stats-grid">
      <div class="stat-card island">
        <div class="stat-icon mem"><span class="material-icons">memory</span></div>
        <div class="stat-info">
          <span class="stat-label">Memory Allocated</span>
          <span class="stat-value">{stats.system.mem_allocated}</span>
        </div>
        <div class="stat-detail">Total obtained: {stats.system.mem_sys}</div>
      </div>
      <div class="stat-card island">
        <div class="stat-icon proc"><span class="material-icons">account_tree</span></div>
        <div class="stat-info">
          <span class="stat-label">Active Routines</span>
          <span class="stat-value">{stats.system.num_goroutine}</span>
        </div>
        <div class="stat-detail">Concurrent background processes</div>
      </div>
      <div class="stat-card island">
        <div class="stat-icon gc"><span class="material-icons">cleaning_services</span></div>
        <div class="stat-info">
          <span class="stat-label">Last GC Pause</span>
          <span class="stat-value">{stats.system.pause_ns}</span>
        </div>
        <div class="stat-detail">Next run at {stats.system.next_gc}</div>
      </div>
    </div>

    {#if feedback}
      <div class="alert {feedback.type}" in:fly={{ y: -10 }}>
        <span class="material-icons">{feedback.type === 'success' ? 'check_circle' : 'error'}</span>
        {feedback.msg}
      </div>
    {/if}

    <div class="operations-list island">
      <h3 class="island-title">Maintenance Operations</h3>
      <div class="ops-grid">
        {#each operations as op}
          <div class="op-card">
            <div class="op-main">
              <span class="material-icons op-icon">{op.icon}</span>
              <div class="op-info">
                <h4>{op.name}</h4>
                <p>{op.desc}</p>
              </div>
            </div>
            <button 
              class="btn-run" 
              onclick={() => runOperation(op.id)}
              disabled={runningOp !== null}
            >
              {#if runningOp === op.id}
                <div class="spinner"></div>
              {:else}
                Run
              {/if}
            </button>
          </div>
        {/each}
      </div>
    </div>
  {/if}
</div>

