<script lang="ts">
  import { apiFetch } from "$lib/api";
  import { onMount } from "svelte";
  import { i18n } from "$lib/i18n.svelte";
  import { dialog } from '$lib/dialog.svelte';
  import Card from './ui/Card.svelte';
  import Button from './ui/Button.svelte';
  import PageHeader from './ui/PageHeader.svelte';

  let stats = $state<any>(null);
  let loading = $state(true);
  let runningOp = $state<number | null>(null);
  let activityLog = $state<
    { msg: string; type: "info" | "success" | "error"; time: string }[]
  >([]);

  const operations = [
    { id: 1, name: "Clean Inactive Accounts", icon: "person_remove", color: "#6366f1", desc: "Permanently delete accounts that have not been activated." },
    { id: 2, name: "Clean Repository Archives", icon: "inventory_2", color: "#8b5cf6", desc: "Remove all repository archives generated by users." },
    { id: 3, name: "Clean Missing Repositories", icon: "folder_off", color: "#f43f5e", desc: "Remove records that have lost their physical Git files." },
    { id: 4, name: "Git Garbage Collection", icon: "cleaning_services", color: "#10b981", desc: 'Run "git gc" across all repositories to optimize storage.' },
    { id: 5, name: "Resync SSH Keys", icon: "key", color: "#f59e0b", desc: 'Rewrite the ".ssh/authorized_keys" file with Ggit keys.' },
    { id: 6, name: "Resync Repository Hooks", icon: "link", color: "#3b82f6", desc: "Resync all Git hooks across all repositories." },
    { id: 8, name: "Resync Repository Stats", icon: "query_stats", color: "#06b6d4", desc: "Update repository sizes, issues and other system-wide counters." },
    { id: 9, name: "Git Health Check (FSCK)", icon: "health_and_safety", color: "#f97316", desc: 'Run "git fsck" to verify object integrity across all repositories.' },
    { id: 10, name: "Metadata Backup", icon: "cloud_download", color: "#ec4899", desc: "Download a ZIP archive with the database, attachments and avatars." },
  ];

  async function fetchStats() {
    try {
      const res = await apiFetch("/api/v2/admin/stats");
      if (res.ok) stats = await res.json();
    } catch (e) {
      logActivity("Failed to fetch system stats", "error");
    } finally {
      loading = false;
    }
  }

  function logActivity(msg: string, type: "info" | "success" | "error" = "info") {
    const time = new Date().toLocaleTimeString();
    activityLog = [{ msg, type, time }, ...activityLog].slice(0, 50);
  }

  async function runOperation(op: any) {
    if (runningOp !== null) return;
    if (!await dialog.confirm(`Are you sure you want to run: ${op.name}?`)) return;
    
    runningOp = op.id;
    logActivity(`Starting: ${op.name}...`, "info");

    if (op.id === 10) {
      try {
        const res = await fetch("/api/v2/admin/backup/export");
        if (res.ok) {
          const blob = await res.blob();
          const url = window.URL.createObjectURL(blob);
          const a = document.createElement('a');
          a.href = url;
          a.download = `ggit-metadata-backup-${new Date().toISOString().split('T')[0]}.zip`;
          document.body.appendChild(a);
          a.click();
          a.remove();
          logActivity(`Completed: ${op.name}`, "success");
        } else {
          logActivity(`Failed: ${op.name} - Server error`, "error");
        }
      } catch (e) {
        logActivity(`Network error: ${op.name}`, "error");
      } finally {
        runningOp = null;
      }
      return;
    }

    try {
      const res = await apiFetch("/api/v2/admin/operations", { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ op: op.id }) });
      if (res.ok) { logActivity(`Completed: ${op.name}`, "success"); await fetchStats(); }
      else { const data = await res.json(); logActivity(`Failed: ${op.name} - ${data.error || "Unknown"}`, "error"); }
    } catch (e) { logActivity(`Network error: ${op.name}`, "error"); } finally { runningOp = null; }
  }

  onMount(fetchStats);
</script>

<div class="maintenance-view-wrapper">
  <div class="admin-maintenance-container">
    <PageHeader 
      title={i18n.t('admin.maintenance') || "Mantenimiento del Sistema"}
      subtitle="Operaciones críticas y optimización de la instancia"
      icon="build"
    />

    <div class="admin-maintenance-body">

    {#if loading}
       <div class="skeleton-grid"></div>
    {:else}
      <div class="stats-row">
        <div class="stat-bubble tonal">
          <span class="material-symbols-rounded">memory</span>
          <div class="stat-info">
            <span class="label">Memoria</span>
            <span class="value">{stats?.system?.mem_allocated || '—'}</span>
          </div>
        </div>
        <div class="stat-bubble tonal">
          <span class="material-symbols-rounded">account_tree</span>
          <div class="stat-info">
            <span class="label">Goroutines</span>
            <span class="value">{stats?.system?.num_goroutine || '—'}</span>
          </div>
        </div>
        <div class="stat-bubble tonal">
          <span class="material-symbols-rounded">schedule</span>
          <div class="stat-info">
            <span class="label">Uptime</span>
            <span class="value">{stats?.system?.uptime || '—'}</span>
          </div>
        </div>
      </div>

      <div class="ops-layout">
        <div class="ops-grid">
          {#each operations as op}
            <div class="op-bubble island">
              <div class="op-icon" style="background: {op.color}20; color: {op.color}">
                <span class="material-symbols-rounded">{op.icon}</span>
              </div>
              <div class="op-text">
                <h4>{op.name}</h4>
                <p>{op.desc}</p>
              </div>
              <Button 
                variant="primary" 
                size="sm" 
                onclick={() => runOperation(op)} 
                disabled={runningOp !== null}
              >
                {runningOp === op.id ? 'Ejecutando...' : 'Ejecutar'}
              </Button>
            </div>
          {/each}
        </div>

        <aside class="console-box">
          <div class="console-header">
            <span>Terminal de Actividad</span>
            <button onclick={() => activityLog = []}>Limpiar</button>
          </div>
          <div class="console-content">
            {#each activityLog as entry}
              <div class="log-line {entry.type}">
                <span class="time">[{entry.time}]</span> {entry.msg}
              </div>
            {/each}
            {#if activityLog.length === 0}
               <div class="empty-log">Esperando operaciones...</div>
            {/if}
          </div>
        </aside>
      </div>
    {/if}
    </div>
  </div>
</div>

