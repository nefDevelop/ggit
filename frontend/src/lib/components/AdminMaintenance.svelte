<script lang="ts">
  import { apiFetch } from "$lib/api";
  import { onMount } from "svelte";
  import { fly, fade } from "svelte/transition";
  import { i18n } from "$lib/i18n.svelte";

  let stats = $state<any>(null);
  let loading = $state(true);
  let runningOp = $state<number | null>(null);
  let activityLog = $state<
    { msg: string; type: "info" | "success" | "error"; time: string }[]
  >([]);

  const operations = [
    {
      id: 1,
      name: "Clean Inactive Accounts",
      icon: "person_remove",
      color: "#6366f1",
      desc: "Permanently delete accounts that have not been activated.",
    },
    {
      id: 2,
      name: "Clean Repository Archives",
      icon: "inventory_2",
      color: "#8b5cf6",
      desc: "Remove all repository archives generated by users.",
    },
    {
      id: 3,
      name: "Clean Missing Repositories",
      icon: "folder_off",
      color: "#f43f5e",
      desc: "Remove records that have lost their physical Git files.",
    },
    {
      id: 4,
      name: "Git Garbage Collection",
      icon: "cleaning_services",
      color: "#10b981",
      desc: 'Run "git gc" across all repositories to optimize storage.',
    },
    {
      id: 5,
      name: "Resync SSH Keys",
      icon: "key",
      color: "#f59e0b",
      desc: 'Rewrite the ".ssh/authorized_keys" file with Ggit keys.',
    },
    {
      id: 6,
      name: "Resync Repository Hooks",
      icon: "link",
      color: "#3b82f6",
      desc: "Resync all Git hooks across all repositories.",
    },
    {
      id: 7,
      name: "Reinitialize Missing Repos",
      icon: "restart_alt",
      color: "#ec4899",
      desc: "Reinitialize Git files for missing records.",
    },
    {
      id: 8,
      name: "Resync Repository Stats",
      icon: "query_stats",
      color: "#06b6d4",
      desc: "Update repository sizes, issues and other system-wide counters.",
    },
    {
      id: 9,
      name: "Git Health Check (FSCK)",
      icon: "health_and_safety",
      color: "#f97316",
      desc: 'Run "git fsck" to verify object integrity across all repositories.',
    },
  ];

  async function fetchStats() {
    try {
      const res = await apiFetch("/api/v2/admin/stats");
      if (res.ok) {
        stats = await res.json();
      }
    } catch (e) {
      logActivity("Failed to fetch system stats", "error");
    } finally {
      loading = false;
    }
  }

  function logActivity(
    msg: string,
    type: "info" | "success" | "error" = "info",
  ) {
    const time = new Date().toLocaleTimeString();
    activityLog = [{ msg, type, time }, ...activityLog].slice(0, 50);
  }

  async function runOperation(op: any) {
    if (runningOp !== null) return;

    const confirmMsg = `Are you sure you want to run: ${op.name}?`;
    if (!confirm(confirmMsg)) return;

    runningOp = op.id;
    logActivity(`Starting operation: ${op.name}...`, "info");

    try {
      const res = await apiFetch("/api/v2/admin/operations", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ op: op.id }),
      });
      const data = await res.json();
      if (res.ok) {
        logActivity(`Successfully completed: ${op.name}`, "success");
        await fetchStats();
      } else {
        logActivity(
          `Failed: ${op.name} - ${data.error || "Unknown error"}`,
          "error",
        );
      }
    } catch (e) {
      logActivity(`Network error during: ${op.name}`, "error");
    } finally {
      runningOp = null;
    }
  }

  onMount(fetchStats);
</script>

