      </div>
    </div>

    <div class="main-layout">
      <!-- OPERATIONS GRID -->
      <section class="ops-section">
        <h2 class="section-title">Core Operations</h2>
        <div class="ops-grid">
          {#each operations as op}
            <div class="op-card tonal">
              <div
                class="op-icon"
                style="background: {op.color}20; color: {op.color}"
              >
                <span class="material-symbols-rounded">{op.icon}</span>
              </div>
              <div class="op-info">
                <h3>{op.name}</h3>
                <p>{op.desc}</p>
              </div>
              <button
                class="btn-action"
                style="--color: {op.color}"
                onclick={() => runOperation(op)}
                disabled={runningOp !== null}
              >
                {#if runningOp === op.id}
                  <span class="spinnerSmall"></span>
                {:else}
                  Run
                {/if}
              </button>
            </div>
          {/each}
        </div>
      </section>

      <!-- ACTIVITY LOG / CONSOLE -->
      <aside class="activity-section">
        <div class=" console">
          <header class="console-header">
            <h3>Activity Log</h3>
            <button class="btn-clear" onclick={() => (activityLog = [])}
              >Clear</button
            >
          </header>
          <div class="console-content">
            {#if activityLog.length === 0}
              <div class="empty-log">Waiting for operations...</div>
            {/if}
            {#each activityLog as entry}
              <div class="log-entry {entry.type}" in:fade>
                <span class="time">[{entry.time}]</span>
                <span class="msg">{entry.msg}</span>
              </div>
            {/each}
          </div>
        </div>
      </aside>
    </div>
  {/if}
</div>

